import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('My Space returns from a nested folder or document to the root listing', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('treeitem', { name: '归档', exact: true }).click();
  await expect(page.locator('.breadcrumbs')).toContainText('归档');
  await expect(page.locator('.space-row')).not.toHaveClass(/selected/);
  await page.locator('.space-row').click();
  await expect(page.locator('.listing-heading h1')).toHaveText('我的空间');
  await expect(page.locator('.breadcrumbs')).toHaveText('我的空间');
  await expect(page.locator('.space-row')).toHaveAttribute('aria-current', 'page');
  await expect(page.locator('.folder-row.selected')).toHaveCount(0);
  await expect(page.locator('.listing-page').getByRole('button', { name: '我的笔记', exact: true })).toBeVisible();
  await page.getByRole('treeitem', { name: '我的笔记', exact: true }).click();
  await page.getByRole('treeitem', { name: '随手记.txt', exact: true }).click();
  await expect(page.getByRole('button', { name: '编辑', exact: true })).toBeVisible();
  await page.locator('.breadcrumbs').getByRole('button', { name: '我的空间', exact: true }).click();
  await expect(page.locator('.listing-heading h1')).toHaveText('我的空间');
  await expect(page.locator('.document-page')).toHaveCount(0);
  await page.screenshot({ path: test.info().outputPath('my-space.png') });
});

test('TXT edits literal text, autosaves and creates history only on Ctrl+S', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('treeitem', { name: '我的笔记', exact: true }).click();
  await page.getByRole('treeitem', { name: '随手记.txt', exact: true }).click();
  const editor = page.locator('.cm-content');
  await expect(editor).toHaveAttribute('contenteditable', 'false');
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await expect(editor).toHaveAttribute('contenteditable', 'true');
  await editor.click();
  await editor.press('Control+End');
  await page.keyboard.insertText('\n# 这是普通文本\n**保留星号**\n- [ ] 保留任务语法');
  await expect(editor).toContainText('**保留星号**');
  await expect(page.locator('.cm-checkbox,.cm-center-line')).toHaveCount(0);
  await expect(page.locator('.save-state')).toHaveText('已保存');
  await page.getByRole('button', { name: '版本历史', exact: true }).click();
  await expect(page.locator('.history-version')).toHaveCount(1);
  await page.getByRole('button', { name: '关闭版本历史' }).click();
  await editor.press('Control+s');
  await expect(page.getByText('已保存版本快照', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '版本历史', exact: true }).click();
  await expect(page.locator('.history-version')).toHaveCount(2);
  await page.getByRole('button', { name: '关闭版本历史' }).click();
  await page.getByRole('button', { name: '预览', exact: true }).click();
  await expect(editor).toHaveAttribute('contenteditable', 'false');
  await page.getByRole('button', { name: '在文档中查找', exact: true }).click();
  await page.getByRole('textbox', { name: '在文档中查找' }).fill('星号');
  await expect(page.locator('.preview-find-box')).toContainText('1/1');
  await page.getByRole('button', { name: '关闭查找' }).click();
  await page.getByRole('button', { name: '重新加载预览', exact: true }).click();
  await expect(editor).toContainText('**保留星号**');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载文件', exact: true }).click();
  const file = await downloading;
  expect(await readFile((await file.path())!, 'utf8')).toContain('# 这是普通文本\n**保留星号**\n- [ ] 保留任务语法');
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(editor).toHaveAttribute('contenteditable', 'true');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('text-editor-mobile.png') });
});
